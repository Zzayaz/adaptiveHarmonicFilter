import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv(
    "/data.txt",
    sep=r"\s+",
    engine="python"
)

df.head()

time = df["time"].values
signal = df["V(N001,N002)"].values

dt = np.diff(time)

print(dt.min())
print(dt.max())

Fs = 50000          # choose sampling frequency (Hz)
dt = 1/Fs

t_uniform = np.arange(time[0], time[-1], dt)

signal_uniform = np.interp(
    t_uniform,
    time,
    signal
) #interpolated signal

time = t_uniform
signal = signal_uniform

signal = signal - np.mean(signal) # dc offset removal

N = len(signal)

fft = np.fft.rfft(signal)

freq = np.fft.rfftfreq(N, d=1/Fs)

magnitude = np.abs(fft) * 2 / N

plt.figure(figsize=(12,5))

plt.plot(freq, magnitude)

plt.xlim(0,500)
plt.xticks(np.arange(0,501,50))
plt.xlabel("Frequency (Hz)")

plt.ylabel("Magnitude")
plt.ylim(0,800)
plt.yticks(np.arange(0,801,50))

plt.grid(True)

plt.show()

fundamental = 50

orders = np.arange(1,21)

harmonics = []

for order in orders:

    target = order*fundamental

    idx = np.argmin(np.abs(freq-target))

    harmonics.append(magnitude[idx])

harmonics = np.array(harmonics)

for order, amp in zip(orders, harmonics):
    print(
        f"H{order:2d}  "
        f"{order*fundamental:6.1f} Hz  "
        f"{amp:.4f}"
    )

plt.figure(figsize=(10,4))

plt.bar(orders, harmonics)

plt.xlabel("Harmonic Order")
plt.xlim(0,15)
plt.xticks(np.arange(0,16,1))

plt.ylabel("Magnitude")

plt.grid(True)

plt.show()

V1 = harmonics[0]

THD = np.sqrt(np.sum(harmonics[1:]**2))/V1*100

print(f"THD = {THD:.2f}%")